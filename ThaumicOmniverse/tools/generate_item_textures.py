"""Recolor verified upstream sprites with Aseprite; do not redraw their geometry.

Run with --group tools|compasses|certificate, or omit it to rebuild all three.
ASEPRITE and MINECRAFT_CLIENT_JAR can override the local executable/client paths.
The hand-authored brass override is intentionally not regenerated by this script.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/main/resources/assets/thaumicomniverse'
ASEPRITE = Path(os.environ.get('ASEPRITE', 'E:/MinecraftResources/Aseprite/App/aseprite.exe'))
VANILLA = Path(os.environ.get('MINECRAFT_CLIENT_JAR',
    'E:/MC/Minecraft 1.20.1 Thaumcraft Extends/.minecraft/versions/1.20.1-Forge/1.20.1-Forge.jar'))


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def generate(group='all'):
    output = ASSETS / 'textures/item'
    output.mkdir(parents=True, exist_ok=True)
    provenance = []
    with tempfile.TemporaryDirectory(prefix='omniverse-recolor-') as folder:
        source = Path(folder)

        def extract(jar, entry, name):
            with ZipFile(jar) as archive:
                data = archive.read(entry)
            (source / name).write_bytes(data)
            provenance.append({'jar': str(jar), 'entry': entry, 'sha256': hashlib.sha256(data).hexdigest()})
            return data

        if group in ('all', 'tools'):
            extract(ROOT / 'evidence/collab-jars/farmersdelight-local.jar',
                    'assets/farmersdelight/textures/item/iron_knife.png', 'iron_knife.png')
            extract(ROOT / 'evidence/collab-jars/mekanismtools-local.jar',
                    'assets/mekanismtools/textures/item/iron_paxel.png', 'iron_paxel.png')
        if group in ('all', 'certificate'):
            gtm = ROOT / 'evidence/modern-jars/gtceu-1.20.1-7.5.3.jar'
            extract(gtm, 'assets/gtceu/textures/item/nan_certificate.png', 'nan_certificate.png')
            with ZipFile(gtm) as archive:
                metadata = archive.read('assets/gtceu/textures/item/nan_certificate.png.mcmeta')
            # Keep all nine original frames and the original long first-frame pause.
            (output / 'thaumaturge_certificate.png.mcmeta').write_bytes(metadata)
        if group in ('all', 'compasses'):
            for angle in range(32):
                name = f'compass_{angle:02}.png'
                extract(VANILLA, 'assets/minecraft/textures/item/' + name, name)
            with ZipFile(VANILLA) as archive:
                vanilla_model = json.loads(archive.read('assets/minecraft/models/item/compass.json'))
            for name in ('sinister_compass', 'primal_compass'):
                for angle in range(32):
                    frame = f'{name}_{angle:02}'
                    write(ASSETS / f'models/item/{frame}.json', {'parent': 'minecraft:item/generated',
                          'textures': {'layer0': f'thaumicomniverse:item/{frame}'}})
                    if name == 'primal_compass':
                        write(output / f'{frame}.png.mcmeta', {'animation': {'frametime': 3, 'interpolate': False}})
                # Vanilla angle zero uses frame 16. Half-frame thresholds and wraparound
                # must travel with the vanilla pixels, rather than the previous art's LUT.
                overrides = []
                for override in vanilla_model['overrides']:
                    vanilla_name = override['model'].split('/')[-1]
                    suffix = '16' if vanilla_name == 'compass' else vanilla_name[-2:]
                    overrides.append({'predicate': override['predicate'],
                                      'model': f'thaumicomniverse:item/{name}_{suffix}'})
                write(ASSETS / f'models/item/{name}.json', {'parent': 'minecraft:item/generated',
                      'textures': {'layer0': f'thaumicomniverse:item/{name}_16'}, 'overrides': overrides})
        lua = source / 'recolor.lua'
        prefix = (f'local SRC = {json.dumps(source.as_posix() + "/")}\n'
                  f'local OUT = {json.dumps(output.as_posix() + "/")}\n'
                  f'local GROUP = {json.dumps(group)}\n')
        lua.write_text(prefix + Path(__file__).with_name('recolor_items.lua').read_text(encoding='utf-8'), encoding='utf-8')
        subprocess.run([str(ASEPRITE), '--batch', '--script', str(lua)], check=True)
    print(json.dumps({'group': group, 'sources': provenance}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--group', choices=('all', 'tools', 'compasses', 'certificate'), default='all')
    generate(parser.parse_args().group)
